/** Largest Lorenz exponent at σ=10, ρ=28, β=8/3 (≈0.9056 per unit time): the λ scale for λτ. MODEL choice. */
export const LORENZ_LAMBDA_MAX=.9056;
/** |v|/c of a channel at 1.0: MODEL choice (a creature is not a relativistic body; this only sets the scale of K). */
export const PSI_BETA_MAX=.1;
/** Gain of the ψ → coherence-target modulation in the integrator. Bounded: |Δtarget| ≤ gain/2. MODEL. */
export const PSI_GAIN=.10;
export const PSI_CHANNELS=Object.freeze(['valence','arousal','dominance','quantum_entropy','phi_harmonics','coherence','chaos','instability','curiosity','resonance','avoid']);
const kineticK=(b2,lt)=>(1+PHI_GOLDEN+lt)*(.5*b2)/(1+lt); // = K_i with m cancelled and v = βc
const REF=kineticK(PSI_CHANNELS.length*(.5*PSI_BETA_MAX)**2,.5*LORENZ_LAMBDA_MAX); // K with every channel at 0.5
/** The creature's kinetic/chaotic ψ term K (dimensionless, ≥0), from its channels. */
export function creaturePsiK(ch){
 let b2=0;for(const k of PSI_CHANNELS){const x=Math.min(1,Math.max(0,Number(ch[k])||0))*PSI_BETA_MAX;b2+=x*x;}
 const lt=Math.min(1,Math.max(0,Number(ch.chaos)||0))*LORENZ_LAMBDA_MAX; // τ = 1
 return kineticK(b2,lt);
}
/** ψn ∈ (0,1): K/(K+K_ref); 0.5 when every channel sits at 0.5. Monotone, rational, deterministic. MODEL. */
export function creaturePsi(ch){const k=creaturePsiK(ch);return k/(k+REF);}
/** Bounded additive nudge to the coherence/Hebbian target: gain·(ψn−0.5), |value| ≤ gain/2. */
export const psiNudge=(ch,gain=PSI_GAIN)=>gain*(creaturePsi(ch)-.5);
