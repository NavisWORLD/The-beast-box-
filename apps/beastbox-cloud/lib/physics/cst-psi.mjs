export const PSI_CONST=Object.freeze({G:6.67430e-11,C:2.99792458e8,K_B:1.380649e-23,HBAR:1.054571817e-34,T_CMB:2.725,
 MPC:3.0856775814913673e22});
export const LN_2=Math.log(2);
export const L_PLANCK=Math.sqrt(PSI_CONST.HBAR*PSI_CONST.G/PSI_CONST.C**3);
export const PHI_GOLDEN=(1+Math.sqrt(5))/2;

/** Bekenstein–Hawking entropy in bits of a sphere of radius R [m]. Dimensionless. */
export function bekensteinBits(radius){
 const {C,HBAR,G}=PSI_CONST;
 return C**3*(4*Math.PI*radius**2)/(4*HBAR*G*LN_2);
}
/** Symmetric Euclidean distances from the SAME position vectors (any dimension). */
export function pairwiseDistances(positions){
 const n=positions.length,d=Array.from({length:n},()=>new Array(n).fill(0));
 for(let i=0;i<n;i++)for(let j=0;j<n;j++){let s=0;for(let k=0;k<positions[i].length;k++){const q=positions[i][k]-positions[j][k];s+=q*q;}d[i][j]=Math.sqrt(s);}
 return d;
}
/** Port of cst_psi.psi_terms. Arrays in, {K,S,U,I,psi} arrays out. Throws on coincident entities (r_ij must be > 0). */
export function psiTerms({masses,positions,velocities,radii,lyapunovs},{phi=PHI_GOLDEN,tau=1,r0=PSI_CONST.MPC,ell=L_PLANCK}={}){
 const {G,C,K_B,T_CMB}=PSI_CONST,n=masses.length,r=pairwiseDistances(positions);
 for(let i=0;i<n;i++)for(let j=0;j<n;j++)if(i!==j&&!(r[i][j]>0))throw new Error('coincident entities: r_ij must be > 0');
 const N=radii.map(bekensteinBits),K=[],S=[],U=[],I=[],P=[];
 for(let i=0;i<n;i++){
  const m=masses[i],lam=lyapunovs[i],eRef=m*C**2*(1+lam*tau);
  let v2=0;for(const x of velocities[i])v2+=x*x;
  const k=(1+phi+lam*tau)*(.5*m*v2)/eRef;
  let s=0,u=0,inf=0;
  for(let j=0;j<n;j++){if(j===i)continue;
   const gp=G*m*masses[j]/r[i][j];
   s+=Math.exp(-r[i][j]/r0)*gp;u+=gp;inf+=K_B*T_CMB*N[i]*N[j]*ell/r[i][j];}
  K.push(k);S.push(s/eRef);U.push(-u/eRef);I.push(-inf/eRef);P.push(k+s/eRef-u/eRef-inf/eRef);
 }
 return {K,S,U,I,psi:P};
}
export const psi=(sys,params)=>psiTerms(sys,params).psi;

