// Generates lib/universe/vislife-look-data.mjs from lib/universe/data/vislife.json (Cosmo's Visual Life look pack, SEEDED look-hints; the engine's own values win).
// Usage: node scripts/gen-vislife-look.mjs   (reads the JSON next to the lib, writes the .mjs, records the sha256 of the JSON in the header)
import {readFileSync,writeFileSync} from 'node:fs';import {createHash} from 'node:crypto';
const src=new URL('../lib/universe/data/vislife.json',import.meta.url),out=new URL('../lib/universe/vislife-look-data.mjs',import.meta.url);
const raw=readFileSync(src);const sha=createHash('sha256').update(raw).digest('hex');const d=JSON.parse(raw);
const blocks=['HERO','SAME_WORLD','ATMOSPHERE','WATER','EVENTS'];
let t=`// GENERATED by scripts/gen-vislife-look.mjs from lib/universe/data/vislife.json. Do not edit by hand.
// source: Cosmo's vislife look pack v${d.version} (${d.pack}), sha256 ${sha}
// label: SEEDED look-hints (a designed look, never a measurement). The engine's own values (skyAt, seaFrom, waveHeightAt, boomState, atmosphere) WIN over any number here.
// The only RECORDED thing behind the pack is the genesis seed (ibm_marrakesh job ${d.seed.source.job_id}) feeding small deterministic jitter. Not live quantum input.
export const VL_PACK=Object.freeze({version:${d.version},sha256:'${sha}',label:'SEEDED'});
export const VL_CLASS=${JSON.stringify(d.class_mapping)};
`;
for(const b of blocks)t+=`export const VL_${b}=${JSON.stringify(d[b])};\n`;
writeFileSync(out,t);console.log('wrote',out.pathname,t.length,'bytes sha',sha.slice(0,12));
