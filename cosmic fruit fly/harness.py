"""Cosmic Fruit Fly: isolated, deterministic, fail-closed experiment harness.

Only the referenced Beast Box dyn12 function is imported from the parent project.
The discrete-time neuron network, environment, policy and plasticity are
computational assumptions, not measured Drosophila physiology.
"""
