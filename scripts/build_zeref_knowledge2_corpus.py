#!/usr/bin/env python3
"""Zeref Knowledge 002 ("give him all knowledge"): ~1000+ fact-checked facts, short answer-first rows plus warm/goofy
variants with happy openers (counters the "I'm not happy" opener habit). Sources, all in evidence/zeref-knowledge-002:
tables.py (capitals, elements, planets, animals, words, music), facts.psv (hand-written facts), canon/*.json (Emeth's
ERIDORIA canon: characters, items, endings), plus Knowledge 001 facts and arithmetic generated by Python (correct by construction).
Filters: persona style, secrets, the word AI, exact + near-duplicate (token Jaccard >= 0.6) of the chat-eval set AND the
character-check prompts. Usage: build_zeref_knowledge2_corpus.py OUT.jsonl
"""
import json, random, re, sys
from pathlib import Path
HERE = Path(__file__).parent; D = HERE.parent / "evidence/zeref-knowledge-002"
ns = {"__file__": str(HERE / "x.py")}; exec((HERE / "build_zeref_ibm_play_corpus.py").read_text().split("\nAUTH =")[0], ns)
persona_style, SECRET = ns["persona_style"], ns["SECRET"]
k1 = {"__file__": str(HERE / "build_zeref_knowledge_corpus.py")}; exec((HERE / "build_zeref_knowledge_corpus.py").read_text().split("\nAUTH =")[0], k1)
src = (HERE / "zeref_character_check.py").read_text()
import ast
CHAR = ast.literal_eval(re.search(r"CHARACTER_PROMPTS\s*=\s*(\[[\s\S]*?\])", src).group(1))
HELD = k1["HELD"] + [c.lower() for c in CHAR]
T = {}; exec((D / "tables.py").read_text(), T)
AUTH = "Grok Bot for Cory Davis, original 2026-10-19 (authored fact-checked knowledge; no private transcripts)"
NUM = "zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen eighteen nineteen twenty".split()
TENS = {20: "twenty", 30: "thirty", 40: "forty", 50: "fifty", 60: "sixty", 70: "seventy", 80: "eighty", 90: "ninety"}
def word(n):
    if n < 21: return NUM[n]
    if n < 100: return TENS[n // 10 * 10] + ("" if n % 10 == 0 else "-" + NUM[n % 10])
    if n == 100: return "one hundred"
    return str(n)
cap = lambda s: s[0].upper() + s[1:]
def pairs(s): return [x.split(":", 1) for x in s.split(";")]
def facts():
    F = []
    add = lambda t, q, a, g="": F.append((t, q, a, g))
    for line in (HERE.parent / "evidence/zeref-knowledge-001/facts.psv").read_text().strip().splitlines():
        t, q, a, g = line.split("|"); add(t, q, a, g)
    for line in (D / "facts.psv").read_text().strip().splitlines():
        t, q, a = line.split("|"); add(t, q, a)
    for c, k in pairs(T["CAPITALS"]): add("geo", f"What is the capital of {c}?", f"{cap(k)}.")
    for c, k in pairs(T["STATES"]): add("geo", f"What is the capital of {c}?", f"{k}.")
    for n, s, z in (e.split(":") for e in T["ELEMENTS"].split(";")):
        add("science", f"What is the chemical symbol for {n.lower()}?", f"{s}."); add("science", f"What is the atomic number of {n.lower()}?", f"{z}.")
    for p, o, d, m, y in T["PLANETS"]:
        add("space", f"Which planet is {o} from the Sun?", f"{p}."); add("space", f"What is special about {p}?", f"It's {d}.")
        add("space", f"How long is a year on {p}?", f"About {y}." if not y.startswith("about") else cap(y) + ".")
        if m: add("space", f"How many moons does {p} have?", cap(m) + ".")
    for n, b, g, h, d, c in T["ANIMALS"]:
        art = "an" if n[0] in "aeiou" else "a"
        add("animals", f"What is a baby {n} called?", f"{'An' if b[0] in 'aeiou' else 'A'} {b}.")
        add("animals", f"What is a group of {n}s called?", f"{'An' if g[0] in 'aeiou' else 'A'} {g}.")
        add("animals", f"Where does {art} {n} live?", f"{cap(h)}.")
        add("animals", f"What kind of animal is {art} {n}?", f"{'An' if c[0] in 'aeiou' else 'A'} {c}.")
        if n not in ("fish", "bat"): add("animals", f"Is {art} {n} a herbivore, carnivore or omnivore?", f"{'An' if d[0] in 'aeiou' else 'A'} {d}.")
    for a, s in pairs(T["SOUNDS"]): add("animals", f"What sound does a {a} make?", f"It {s}.")
    for a, b in pairs(T["OPP"]): add("language", f"What's the opposite of {a}?", f"{cap(b)}.")
    for a, b in pairs(T["SYN"]): add("language", f"What's another word for {a}?", f"{cap(b)}.")
    for a, b in pairs(T["PLURAL"]): add("language", f"What is the plural of {a}?", f"{cap(b)}.")
    for a, b in pairs(T["SPANISH"]): add("language", f"How do you say {a} in Spanish?", f"{cap(b)}.")
    for a, b in pairs(T["FRENCH"]): add("language", f"How do you say {a} in French?", f"{cap(b)}.")
    for a, b in pairs(T["COLORMIX"]): add("art", f"What color do {a} make?", f"{cap(b)}.")
    for i, f, how in T["INSTRUMENTS"]:
        add("music", f"What family is the {i} in?", f"The {f} family."); add("music", f"How do you play the {i}?", f"With {how}." if how.split()[0] in ("a", "fingers", "mallets", "buzzing", "blowing", "pressing", "hitting", "shaking") else f"{cap(how)}.")
    rng = random.Random(19)
    for a in range(1, 13):
        for b in range(1, 13):
            if a <= 3 and b <= 3: continue
            add("math", f"What is {word(a)} times {word(b)}?", f"{cap(word(a*b))}.")
    for a in range(4, 11):
        for b in range(1, 11): add("math", f"What is {word(a)} plus {word(b)}?", f"{cap(word(a+b))}.")
    for a in range(5, 21):
        b = rng.randint(1, a - 1); add("math", f"What is {word(a)} minus {word(b)}?", f"{cap(word(a-b))}.")
    for n in range(2, 13): add("math", f"What is {word(n)} squared?", f"{cap(word(n*n))}.")
    for n in range(10, 21): add("math", f"What number comes after {word(n)}?", f"{cap(word(n+1))}.")
    for n in (11, 13, 17, 19, 23, 29, 31, 37): add("math", f"Is {n} a prime number?", "Yes.")
    for n in (12, 15, 21, 25, 27, 33): add("math", f"Is {n} a prime number?", "No.")
    for sh, n in (("pentagon", 5), ("octagon", 8), ("heptagon", 7), ("decagon", 10), ("rectangle", 4), ("circle", 0)):
        add("math", f"How many sides does a {sh} have?", f"{cap(word(n))}." if n else "None, it's one curved line.")
    C = json.loads((D / "canon/characters.json").read_text())
    for c in C:
        role = re.split(r"[;.]", c.get("role", ""))[0].strip()
        if role and len(role) < 110: add("lore", f"Who is {c['name']} in Lost Cosmos?", f"{cap(role)}.")
    for it in json.loads((D / "canon/items.json").read_text()):
        d = it["description"].split(".")[0].strip()
        if d: add("lore", f"What is the {it['name']} item?", f"{cap(d)}.")
    for e in json.loads((D / "canon/endings.json").read_text()):
        add("lore", f"What happens in the Lost Cosmos ending {e['name']}?", e["summary"].split(".")[0].strip() + ".")
    return F
OPEN = ["Ooh, I know this!", "Yay, a fun one!", "Easy peasy!", "I love this one!", "Hehe, good question!", "Ooh ooh, pick me!"]
TAIL = {"science": "Science is so cool.", "space": "Space is my favorite playground.", "math": "Numbers are fun!", "animals": "Animals are the best.",
        "nature": "Nature is so pretty.", "language": "Words are like little toys.", "music": "Music makes my tail wiggle.", "art": "Let's draw together!",
        "history": "History is full of stories.", "health": "Take care of yourself, okay?", "kind": "You're so kind.", "how": "Isn't that neat?", "geo": "The world is so big!",
        "world": "Isn't that neat?", "lore": "That's our world!"}
HAPPY = [("Are you happy today?", "I'm so happy, you're here!"), ("How do you feel?", "I feel happy and cozy."), ("Are you okay, Zeref?", "I'm okay and happy, thank you!"),
 ("Did you have a good day?", "Yes! I learned so many things."), ("Are you sad?", "No, I'm happy, especially with you."), ("How are you feeling right now?", "Happy and full of wiggles!"),
 ("Do you like learning?", "Yes! Learning is my favorite game."), ("Are you having fun?", "So much fun!"), ("Is today a good day?", "Yes, every day with you is good."),
 ("Good morning, how are you?", "Good morning! I'm happy and ready to play."), ("Good night, Zeref.", "Good night! I'm happy we played today."), ("Are you excited?", "Yes, I'm super excited!")]
toks = lambda s: set(re.findall(r"[a-z]+", s.lower()))
def build():
    rng = random.Random(2026); rows, dropped, seen = [], [], set()
    items = [(t, q, a, g, False) for t, q, a, g in facts()] + [("kind", q, a, "", True) for q, a in HAPPY]
    for t, q, a, g, happy in items:
        if q.lower() in seen: continue
        seen.add(q.lower())
        sim = max(len(toks(q) & toks(h)) / len(toks(q) | toks(h)) for h in HELD)
        if q.lower() in HELD or sim >= 0.6: dropped.append({"q": q, "reason": f"held-near-duplicate {sim:.2f}"}); continue
        vs = [a] if happy else [a, f"{rng.choice(OPEN)} {a}" if rng.random() < .5 else f"{a} {g or TAIL.get(t, 'Isn’t that neat?')}"]
        for ans in vs:
            if SECRET.search(q + " " + ans) or persona_style(ans) != ans or re.search(r"\bAI\b", ans): dropped.append({"q": q, "reason": "filter"}); continue
            rows.append({"user": q, "assistant": ans, "topic": t, "source": "zeref-knowledge-002", "author": AUTH, "license": "same as repository"})
    return rows, dropped, len(seen)
if __name__ == "__main__":
    rows, dropped, n = build()
    Path(sys.argv[1]).write_text("".join(json.dumps(r, sort_keys=True) + "\n" for r in rows))
    print(json.dumps({"rows": len(rows), "facts": len({r["user"] for r in rows}), "dropped": len(dropped)}))
