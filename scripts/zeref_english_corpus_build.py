#!/usr/bin/env python3
"""Zeref English foundation corpus 001 (Cory, 2026-11-12 5:51 PM CT: "build Zeref a big English
learning set and train it through the gate").

RECORDED corpus: public text written by people (public-domain books, CC BY 4.0 human dialogue).
It is NOT Zeref's experience and NOT generated by any model. No other model speaks for him.

Sources are fixed below with their licence. Each raw download is hashed into the manifest.
Process: strip Project Gutenberg header/footer and licence (so the text is plain US public domain),
clean, chunk into passages, screen PII (email/URL/phone/long digit runs) and toxicity (hashed
word blocklist; plaintext is not stored in the repo), exact-dedupe, and split ~3% held out by a
stable hash (held out rows are never trained on; they feed the report-only clarity metric).

Usage: zeref_english_corpus_build.py RAW_DIR OUT_DIR
  RAW_DIR holds pg<ID>.txt and tm1-self.json / tm1-woz.json (fetched from the URLs below).
"""
from __future__ import annotations
import gzip,hashlib,json,re,sys,unicodedata
from collections import Counter
from pathlib import Path

LABEL="RECORDED_CORPUS"
LABEL_NOTE="RECORDED corpus: public English written by people. Not Zeref's experience; not model-generated."
SCHEMA="zeref-english-corpus-v1"
# Children's and simple literature first. Public domain in the US (Project Gutenberg);
# titles with heavy slur content (e.g. Huck Finn, Tom Sawyer, Just So Stories, Doctor Dolittle, Peter Pan) are left out.
GUTENBERG=[11,12,55,54,113,45,514,2591,1597,21,19994,289,236,271,146,479,902,1448,1450,1874,778,498,708,500]
GUTENBERG_URL="https://www.gutenberg.org/cache/epub/{id}/pg{id}.txt"
GUTENBERG_LICENCE="Public domain (US); Project Gutenberg header, footer and licence text removed"
TASKMASTER_COMMIT="master"
TASKMASTER={"tm1-self.json":"https://raw.githubusercontent.com/google-research-datasets/Taskmaster/master/TM-1-2019/self-dialogs.json",
            "tm1-woz.json":"https://raw.githubusercontent.com/google-research-datasets/Taskmaster/master/TM-1-2019/woz-dialogs.json"}
TASKMASTER_LICENCE="CC-BY-4.0"
TASKMASTER_ATTRIBUTION=("Taskmaster-1 (2019) by Bill Byrne, Karthik Krishnamoorthi, Chinnadhurai Sankar, Arvind Neelakantan, "
 "Amit Dubey, Kyu-Young Kim and Andy Cedilnik, Google LLC, CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). "
 "Human-written dialogs (crowd workers and call-centre operators). Changes: turns re-joined as 'A:'/'B:' passages, PII-screened.")
# Considered and excluded (recorded so the decision is visible):
EXCLUDED=[
 {"source":"roneneldan/TinyStories","reason":"generated by GPT-3.5/GPT-4 (another model's words). Not added here. NOTE: already used by the existing 007 pretrain slice; owner decision needed."},
 {"source":"OpenAssistant/oasst1","reason":"Apache-2.0, but some 'human' replies are known to be pasted model output; unsure -> excluded"},
 {"source":"DailyDialog","reason":"CC BY-NC-SA (non-commercial)"},
 {"source":"EmpatheticDialogues","reason":"CC BY-NC 4.0 (non-commercial)"},
 {"source":"Cornell Movie-Dialogs","reason":"no clear licence"},
 {"source":"Topical-Chat","reason":"CDLA-Sharing-1.0 (not CC0/CC-BY/Apache)"},
 {"source":"Schema-Guided Dialogue","reason":"CC BY-SA 4.0 (share-alike, not in the allowed list)"},
 {"source":"Simple English Wikipedia","reason":"CC BY-SA (share-alike, not in the allowed list)"},
]
MIN_CHARS,MAX_CHARS=200,900
HELDOUT_PERCENT=3
PII=[("email",re.compile(r"[\w.+-]+@[\w-]+\.[\w.]+")),("url",re.compile(r"https?://|www\.|\.com\b|\.org\b|\.net\b",re.I)),
     ("phone",re.compile(r"\(?\b\d{3}\)?[\s.-]?\d{3}[\s.-]\d{4}\b|\b\d{10,}\b")),("ssn",re.compile(r"\b\d{3}-\d{2}-\d{4}\b"))]
WORD=re.compile(r"[a-z]+(?:-[a-z]+)?")
BLOCK=set(json.loads((Path(__file__).resolve().parents[1]/"evidence/zeref-english-001/screen-blocklist.sha256.json").read_text()))
def sha(b):return hashlib.sha256(b).hexdigest()
def norm_ws(s):
 s=unicodedata.normalize("NFKC",s).replace("\u2019","'").replace("\u2018","'").replace("\u201c",'"').replace("\u201d",'"').replace("\u2014"," - ").replace("\u2013","-")
 s=s.replace("\u2026","...").replace("\u00a0"," ")
 s="".join(c for c in unicodedata.normalize("NFKD",s) if not unicodedata.combining(c))  # cafe, naive: accents dropped
 s=re.sub(r"_([^_]+)_",r"\1",s);s=re.sub(r"\[(Illustration|Footnote)[^\]]*\]","",s,flags=re.I)
 return re.sub(r"\s+"," ",s).strip()
def screen(text):
 for name,rx in PII:
  if rx.search(text):return "pii_"+name
 for w in WORD.findall(text.lower()):
  if sha(w.encode()) in BLOCK:return "toxicity_blocklist"
 if re.search(r"[^\x20-\x7e\n]",text):return "non_ascii"
 letters=sum(c.isalpha() for c in text)
 if letters<.6*len(text):return "low_letters"
 return None
def gutenberg_body(raw):
 t=raw.decode("utf-8","ignore").replace("\r\n","\n")
 a=re.search(r"\*\*\* ?START OF (THE|THIS) PROJECT GUTENBERG[^\n]*\n",t);b=re.search(r"\*\*\* ?END OF (THE|THIS) PROJECT GUTENBERG",t)
 if not a or not b:raise ValueError("Gutenberg markers missing")
 return t[a.end():b.start()]
def passages_from_paragraphs(paras):
 out=[];cur=""
 for p in paras:
  if len(cur)+1+len(p)<=MAX_CHARS:cur=(cur+" "+p).strip()
  else:
   if len(cur)>=MIN_CHARS:out.append(cur)
   cur=p if len(p)<=MAX_CHARS else ""
 if len(cur)>=MIN_CHARS:out.append(cur)
 return out
def book_rows(gid,raw):
 body=gutenberg_body(raw);title=re.search(r"^Title: (.+)$",raw.decode("utf-8","ignore"),re.M)
 paras=[norm_ws(p) for p in re.split(r"\n\s*\n",body)]
 # drop headings, contents lines, all-caps lines and short fragments
 paras=[p for p in paras if len(p)>=40 and not re.match(r"^(CHAPTER|Chapter|BOOK|PART|CONTENTS|THE END|Produced by|Transcriber)",p) and not (p.upper()==p)]
 src=f"gutenberg:{gid}"
 return (title.group(1).strip() if title else src),[{"text":t,"source":src} for t in passages_from_paragraphs(paras)]
def dialog_rows(name,raw):
 rows=[];spk={"USER":"A","ASSISTANT":"B"}
 for conv in json.loads(raw):
  turns=[(spk.get(u.get("speaker"),"A"),norm_ws(u.get("text",""))) for u in conv.get("utterances",[])]
  turns=[(s,t) for s,t in turns if t]
  cur=[]
  for s,t in turns:
   line=f"{s}: {t}"
   if sum(len(x)+1 for x in cur)+len(line)>MAX_CHARS and cur:
    rows.append("\n".join(cur));cur=[]
   cur.append(line)
  if cur:rows.append("\n".join(cur))
 return [{"text":t,"source":"taskmaster-1:"+name} for t in rows if len(t)>=MIN_CHARS//2]
def build(raw_dir,out_dir):
 raw_dir,out_dir=Path(raw_dir),Path(out_dir);out_dir.mkdir(parents=True,exist_ok=True)
 sources=[];cand=[]
 for gid in GUTENBERG:
  raw=(raw_dir/f"pg{gid}.txt").read_bytes();title,rows=book_rows(gid,raw)
  sources.append({"source":f"gutenberg:{gid}","title":title,"url":GUTENBERG_URL.format(id=gid),"licence":GUTENBERG_LICENCE,
   "raw_sha256":sha(raw),"raw_bytes":len(raw),"kind":"book","model_generated":False});cand+=[(r,"book") for r in rows]
 for name,url in TASKMASTER.items():
  raw=(raw_dir/name).read_bytes();rows=dialog_rows(name.split(".")[0],raw)
  sources.append({"source":"taskmaster-1:"+name.split(".")[0],"title":"Taskmaster-1 "+name,"url":url,"licence":TASKMASTER_LICENCE,
   "attribution":TASKMASTER_ATTRIBUTION,"raw_sha256":sha(raw),"raw_bytes":len(raw),"kind":"dialogue","model_generated":False});cand+=[(r,"dialogue") for r in rows]
 seen=set();dropped=Counter();train=[];held=[];per=Counter();per_bytes=Counter()
 lic={s["source"]:s["licence"] for s in sources}
 for r,kind in cand:
  why=screen(r["text"])
  if why:dropped[why]+=1;continue
  key=sha(re.sub(r"[^a-z0-9]","",r["text"].lower()).encode())
  if key in seen:dropped["duplicate"]+=1;continue
  seen.add(key)
  row={"text":r["text"],"source":r["source"],"kind":kind,"licence":lic[r["source"]],"label":LABEL,"row_sha256":sha(r["text"].encode())}
  (held if int(key[:8],16)%100<HELDOUT_PERCENT else train).append(row)
  per[r["source"]]+=1;per_bytes[r["source"]]+=len(r["text"].encode())
 def dump(rows):return "".join(json.dumps(x,sort_keys=True,ensure_ascii=True)+"\n" for x in rows).encode()
 tb=dump(train);hb=dump(held)
 (out_dir/"train.jsonl.gz").write_bytes(gzip.compress(tb,mtime=0))
 (out_dir/"heldout.jsonl").write_bytes(hb)
 # Proxy dictionary for the clarity metric: words seen >=3 times in the public-domain books plus
 # words seen >=20 times in the human dialogue (catches 'okay', 'pizza'). Report-only.
 cb=Counter();cd=Counter()
 for x in train:(cb if x["kind"]=="book" else cd).update(WORD.findall(x["text"].lower()))
 words=sorted({w for w,c in cb.items() if c>=3}|{w for w,c in cd.items() if c>=20})
 wl=("\n".join(words)+"\n").encode();(out_dir/"wordlist.txt").write_bytes(wl)
 for s in sources:s["rows_kept"]=per[s["source"]];s["text_bytes_kept"]=per_bytes[s["source"]]
 kinds=Counter(x["kind"] for x in train)
 man={"schema":SCHEMA,"label":LABEL,"label_note":LABEL_NOTE,"owner_approval":"Cory, 2026-11-12 5:51 PM CT: 'Yes, build Zeref a big English learning set and train it through the gate'",
  "sources":sources,"excluded_sources":EXCLUDED,"licences":sorted(set(lic.values())),
  "screening":{"pii":[n for n,_ in PII],"toxicity":"sha256 word blocklist (evidence/zeref-english-001/screen-blocklist.sha256.json)","non_ascii":True,"dedupe":"exact, normalised alnum sha256","dropped":dict(sorted(dropped.items()))},
  "split":{"heldout_percent":HELDOUT_PERCENT,"rule":"int(sha256(normalised)[:8],16)%100<3 -> heldout (never trained)"},
  "files":{"train.jsonl.gz":{"sha256":sha((out_dir/"train.jsonl.gz").read_bytes()),"bytes":(out_dir/"train.jsonl.gz").stat().st_size,"rows":len(train),"jsonl_sha256":sha(tb),"jsonl_bytes":len(tb)},
           "heldout.jsonl":{"sha256":sha(hb),"bytes":len(hb),"rows":len(held)},
           "wordlist.txt":{"sha256":sha(wl),"bytes":len(wl),"words":len(words)}},
  "train_rows_by_kind":dict(kinds),"train_text_bytes":sum(len(x["text"].encode()) for x in train)}
 (out_dir/"manifest.json").write_text(json.dumps(man,indent=1,sort_keys=True)+"\n")
 print("ZEREF_ENGLISH_CORPUS_BUILT="+json.dumps({"train_rows":len(train),"heldout_rows":len(held),"by_kind":dict(kinds),"dropped":dict(dropped),"train_sha256":man["files"]["train.jsonl.gz"]["sha256"]}))
 return man
if __name__=="__main__":build(sys.argv[1],sys.argv[2])
